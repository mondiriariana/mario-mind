"""RL of the Glimmer agent toward one person's play: one loop, the reward source is the algorithm.

  --algo density  reward = log p_human(x) under a Gaussian mixture fitted once on human turns (no adversary)
  --algo gail     judge D(x) trained each iteration, human vs agent turns (BCE + gradient penalty);
                  reward = -log(1 - D(x))                                       (imitation: GAIL)
  --algo airl     judge logit = f(x, x') - log pi(a|s), f = g(x) + gamma h(s') - h(s);
                  reward = f - log pi(a|s)                                      (imitation: AIRL)
x = (game state at the turn start, previous combo, combo). Game state from RAM, the same function for the
human (features/ram_full) and the agent: Mario position / speed / airborne / size, the 5 nearest enemies
(dx, dy), as in mjg.objects.oracle_objects.
Judge (gail / airl): it learns from the human turns of the same game phase as the agent's (the first --turns turns
after a level start; --judge-all-phases uses the whole level, where the judge can tell agent from human by where
Mario is in the level), takes --judge-steps updates per iteration on the agent turns of the last --judge-replay
iterations, and is scored before its update on turns it has not seen (this iteration's agent turns, the validation
humans of the same phase): judge_heldout_* in the log.

One iteration:
  1. rollout: --games parallel games x --turns turns (a dead game restarts on a new level), Glimmer with the
     current LoRA, sampling (temperature 1, top-p 0.95, top-k 64), turn format of glimmer_play.py
  2. rewards per turn (above), discounted turn returns (--gamma), normalised over the batch
  3. policy update: REINFORCE with the normalised advantage on the mean log-prob of the generated tokens
     (thinking + answer), one pass, LoRA only
  4. human-likeness of this iteration's turns: cross-validated accuracy of a fresh logistic classifier,
     agent vs human (validation plays) on x (0.5 = indistinguishable), and KL of the action histograms
Stop: when the classifier accuracy changes < 0.01 over --patience evaluations, or at --iters.
Starts from the SFT LoRA (--init).

--engine vllm: the rollout replies are generated by a vLLM server (vllm_engine.py) on --gen-gpus while the HF model
that computes log-probs and takes the update lives on --train-gpus; the server gets the new LoRA after every update.
Same prompts, sampling settings and update as --engine hf (default).
--player sub-0X: the "Play like player sub-0X" line, for models trained on several subjects (train_sft.py).
--kl-beta: keeps the policy near the --init model (per-token k3 KL estimate as in GRPO, Shao et al. 2024, added to
the loss), so the update on button rewards does not wear away the reasoning learned in SFT. 0 = off.
Malformed replies: --format-reward sets their reward, --format-mask gives them no policy gradient, --format-guard
rolls the LoRA back when too many rollouts are malformed; --ban-tokens and --force-answer (vLLM) keep the reply
format intact.

Inputs: $MJG_ROOT/features/ram_full, the SFT data (--human-dir, from build_sft.py), the model (--model-dir).
Outputs: <--out-root>/<tag>/ log.json, lora_last.pt, lora_itNNN.pt, lora_clean.pt (--format-guard), state.pt,
rollouts/.
  python rl.py --algo gail --init <SFT lora.pt> --iters 40
  python rl.py --algo gail --init <SFT lora.pt> --engine vllm --gen-gpus 0,1 --train-gpus 2,3 --kl-beta 0.04
"""
