def job_end():
    """Unix time at which this Slurm job is killed (None outside Slurm), as experiments/glimmer_vlajepa/train.py."""
    jid = os.environ.get("SLURM_JOB_ID")
    if not jid:
        return None
    try:
        out = subprocess.run(["squeue", "-h", "-j", jid, "-o", "%e"], capture_output=True, text=True, timeout=60).stdout
        return time.mktime(time.strptime(out.strip(), "%Y-%m-%dT%H:%M:%S"))
    except Exception:
        return None


def images_of(msgs):
    """The images of a chat conversation, in order."""
    imgs = []
    for x in msgs:
        for c in (x["content"] if isinstance(x["content"], list) else []):
            if c.get("type") == "image":
                imgs.append(c["image"])
    return imgs


def lora_state(params, clone=False):
    """{name: CPU copy} of the LoRA tensors."""
    out = {}
    for nm, p in params.items():
        t = p.detach().cpu()
        out[nm] = t.clone() if clone else t
    return out


def load_into(params, sdict):
    """Copy a {name: tensor} state into the LoRA parameters."""
    with torch.no_grad():
        for nm, v in sdict.items():
            params[nm].copy_(v.to(params[nm].device))


def model_kwargs():
    """from_pretrained placement: one GPU if it has > 80 GB (H200), else spread over all visible GPUs."""
    if torch.cuda.get_device_properties(0).total_memory > 80e9:
        return dict(device_map={"": 0})
    max_memory = {}
    for i in range(torch.cuda.device_count()):
        max_memory[i] = "36GiB" if i == 0 else "44GiB"
    return dict(device_map="auto", max_memory=max_memory)


