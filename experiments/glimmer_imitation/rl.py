# ----------------------------------------------------------------------------------------- main
def main():
    # On Hopper GPUs (H200) PyTorch's cuDNN attention backward gives NaN gradients in Glimmer (see
    # experiments/glimmer_vlajepa/train.py); with it off SDPA uses FlashAttention, as on the L40S.
    torch.backends.cuda.enable_cudnn_sdp(False)
    a = parse_args()
    if a.export_human:
        Xh, Sh, S2h, Th = human_turns("train", a.max_human_plays, with_turn=True, data_dir=a.human_dir)
        Xv, _, _, Tv = human_turns("val", a.max_human_plays, with_turn=True, data_dir=a.human_dir)
        levels = levels_of(a.human_dir)
        np.savez_compressed(a.export_human, Xh=Xh, Sh=Sh, S2h=S2h, Th=Th, Xv=Xv, Tv=Tv, levels=np.array(levels))
        print(f"wrote {a.export_human}: train {len(Xh)}, val {len(Xv)} turns, levels {levels}")
        return
    T_START = time.time()
    tag = a.tag or a.algo
    od = f"{a.out_root}/{tag}"
    os.makedirs(od, exist_ok=True)
    say = lambda *x: print(time.strftime("%H:%M:%S"), *x, flush=True)
    srv = None
    if a.engine == "vllm":  # start the server on its GPUs, then keep this process off them (before CUDA is touched)
        import vllm_engine
        job = os.environ.get("SLURM_JOB_ID", "x")
        srv = vllm_engine.Client(a.gen_gpus, a.vllm_tp, f"{TMP}/vllm_{tag}_{job}",
                                 model=a.model_dir, log=f"{od}/vllm_server.log",
                                 # a port per job, so two RL jobs on one node do not collide
                                 port=7000 + int(os.environ.get("SLURM_JOB_ID", "0")) % 2000)
        os.environ["CUDA_VISIBLE_DEVICES"] = a.train_gpus
    random.seed(0)
    torch.manual_seed(0)
    rng = np.random.default_rng(0)

    # human turns (judge / density / evaluation)
    if a.human_feats:
        hf = np.load(a.human_feats)
        Xh, Sh, S2h, Xv = hf["Xh"], hf["Sh"], hf["S2h"], hf["Xv"]
        levels = []
        for lv in hf["levels"]:
            levels.append(str(lv))
        Tv = hf["Tv"] if "Tv" in hf else None
        Th = hf["Th"] if "Th" in hf else None
    else:
        Xh, Sh, S2h, Th = human_turns("train", a.max_human_plays, with_turn=True, data_dir=a.human_dir)
        Xv, _, _, Tv = human_turns("val", a.max_human_plays, with_turn=True, data_dir=a.human_dir)
        levels = levels_of(a.human_dir)
    # the agent's games are a.turns turns from a level start: compare them with the humans' turns from the same phase
    # (else the classifier mostly sees where in the level Mario is, not how he plays)
    Xv_m = Xv[Tv < a.turns] if Tv is not None else None
    mu, sd = Xh.mean(0), Xh.std(0) + 1e-6
    nz = lambda X: (X - mu) / sd
    smu, ssd = Sh.mean(0), Sh.std(0) + 1e-6
    # the judge's humans: the agent's game phase (the first a.turns turns after a level start) unless --judge-all-phases
    if a.algo in ("gail", "airl") and not a.judge_all_phases:
        assert Th is not None, "--human-feats file has no turn index (Th): re-export it, or pass --judge-all-phases"
        jh = Th < a.turns
    else:
        jh = np.ones(len(Xh), bool)
    hum = {"x": torch.tensor(nz(Xh[jh])), "s": torch.tensor((Sh[jh] - smu) / ssd),
           "s2": torch.tensor((S2h[jh] - smu) / ssd)}
    hum_val = None
    if Xv_m is not None and len(Xv_m):  # held-out humans of the agent's phase, to score the judge on unseen turns
        Sv_m = Xv_m[:, :Sh.shape[1]]  # the state is the first part of x (x_of); s2 only matters for airl
        hum_val = {"x": torch.tensor(nz(Xv_m)), "s": torch.tensor((Sv_m - smu) / ssd),
                   "s2": torch.tensor((Sv_m - smu) / ssd)}
    say(f"human turns: train {len(Xh)} (judge: {int(jh.sum())}), val {len(Xv)}; x dim {Xh.shape[1]}; "
        f"levels {len(levels)}")
    if a.algo == "density":
        from sklearn.mixture import GaussianMixture
        gmm = GaussianMixture(32, covariance_type="full", reg_covar=1e-3, random_state=0).fit(nz(Xh))
    else:
        judge = Judge(Xh.shape[1], Sh.shape[1], a.algo == "airl")
        jopt = torch.optim.Adam(judge.parameters(), a.judge_lr)
        ag_buf = []  # agent turns of the last --judge-replay iterations

    # policy
    from transformers import AutoProcessor, AutoModelForImageTextToText
    proc = AutoProcessor.from_pretrained(a.model_dir)
    tok = proc.tokenizer
    if tok.pad_token_id is None:
        tok.pad_token = tok.eos_token
    ban_ids = tok.convert_tokens_to_ids(a.ban_tokens)
    assert tok.unk_token_id not in ban_ids or tok.unk_token_id is None, \
        f"--ban-tokens not in the vocabulary: {a.ban_tokens}"
    ban = {}
    if ban_ids:
        bias = {}
        for i in ban_ids:
            bias[i] = -100.0
        ban = dict(logit_bias=bias)
    if ban:
        say(f"banned tokens {dict(zip(a.ban_tokens, ban_ids))}")
    model = AutoModelForImageTextToText.from_pretrained(a.model_dir, dtype=torch.bfloat16, **model_kwargs())
    model.requires_grad_(False)
    _, layers = find_layers(model, model.config.text_config.num_hidden_layers)
    add_lora(layers, a.r)
    params = {}
    for nm, p in model.named_parameters():
        if nm.endswith((".A", ".B")):
            params[nm] = p
    if a.init:
        sdict = torch.load(a.init)
        load_into(params, sdict)
        say(f"init from {a.init} ({len(sdict)} tensors)")
    model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
    opt = torch.optim.AdamW(params.values(), lr=a.lr, weight_decay=0.0)
    dev = model.get_input_embeddings().weight.device

    import multiprocessing as mp
    ctx = mp.get_context("spawn")
    if a.worker_python:
        ctx.set_executable(a.worker_python)
    gargs = argparse.Namespace(out=f"{od}/rollouts", integration=a.integration, max_turns=10_000, every=10)
    ep_count = [0]

    def new_game(slot, wait=True):
        ep_count[0] += 1
        lv = levels[rng.integers(len(levels))]
        return G.Remote(ctx, gargs, lv, ep_count[0], wait=wait)

    log, hl_hist, start = [], [], 1
    state_path = f"{od}/state.pt"
    # one run per tag at a time (batch job vs an interactive window): a lock refreshed during every iteration;
    # a later run waits for it to go stale or be released, then resumes from the newest state
    lock = f"{od}/RUNNING"
    fresh = lambda: os.path.exists(lock) and time.time() - os.path.getmtime(lock) < 40 * 60
    if fresh():
        say(f"{lock} is fresh ({open(lock).read().strip()}): waiting up to {a.lock_wait} min for the other run")
        t_w = time.time()
        while fresh() and time.time() - t_w < a.lock_wait * 60:
            time.sleep(60)
        if fresh():
            say("still busy; exiting")
            if srv:
                srv.close()
            return
    take_lock = lambda: open(lock, "w").write(os.environ.get("SLURM_JOB_ID", "local"))
    take_lock()
    if a.resume and os.path.exists(f"{od}/DONE"):  # finished earlier (all iterations, or flat): nothing to do
        say(f"{od}/DONE exists: run finished ({open(f'{od}/DONE').read().strip()})")
        os.remove(lock)
        if srv:
            srv.close()
        return
    if a.resume and os.path.exists(state_path):
        st = torch.load(state_path, weights_only=False)
        load_into(params, st["lora"])
        opt.load_state_dict(st["opt"])
        if a.algo != "density":
            judge.load_state_dict(st["judge"])
            jopt.load_state_dict(st["jopt"])
        log, hl_hist, ep_count[0] = st["log"], st["hl_hist"], st["ep_count"]
        rng.bit_generator.state = st["rng"]
        start = st["it"] + 1
        a.kl_beta = st.get("kl_beta", a.kl_beta)  # --format-guard may have raised it
        say(f"resumed from {state_path}: iteration {st['it']} done")
    ref = None  # the --init policy
    if a.kl_beta:
        ref = {}
        for nm, p in params.items():
            ref[nm] = p.detach().clone()
    if a.kl_beta and a.resume and os.path.exists(state_path) and a.init:
        ref = {}
        for nm, v in torch.load(a.init).items():
            ref[nm] = v.to(params[nm].device)

    clean = None  # --format-guard: the last LoRA whose rollouts were at or under the limit (CPU copy)
    if a.format_guard:
        cp = f"{od}/lora_clean.pt"
        clean = torch.load(cp) if (a.resume and os.path.exists(cp)) else lora_state(params, clone=True)

    def push_lora():  # hand the current LoRA to the vLLM server
        torch.save(lora_state(params), f"{od}/lora_policy.pt")
        srv.set_lora(f"{od}/lora_policy.pt")
    if srv:
        say(f"vLLM server ready ({srv.wait():.0f}s) on GPUs {a.gen_gpus}; training on {a.train_gpus}")
        push_lora()
    FORCE = ">\n<answer>"

    def enc(x):
        return tok(x, add_special_tokens=False)["input_ids"]

    def force_answers(texts, msgs, new, seed):
        """--force-answer: replies that stop after </reasoning without a valid answer are cut there, FORCE is appended
        and the model writes the buttons. Returns the new reply ids and, per reply, the (start, end) token span of the
        appended text (None if untouched), which tok_mask() keeps out of the gradient."""
        fix, cuts, prompts = [], [], []
        for s, ids in enumerate(new):
            raw = tok.decode(ids, skip_special_tokens=False)
            if G.parse(G.split_thinking(raw)[1])[2] and "</reasoning" in raw:
                cut = raw[:raw.rindex("</reasoning") + len("</reasoning")]
                fix.append(s)
                cuts.append(cut)
                prompts.append((texts[s] + cut + FORCE, images_of(msgs[s])))
        forced = [None] * len(new)
        if not fix:
            return new, forced
        out2, _ = srv.generate(prompts, temperature=1.0, top_p=0.95, top_k=64, max_tokens=48, stop=["</answer>"],
                               seed=seed + 5_000, **ban)
        for s, c, o in zip(fix, cuts, out2):
            text = c + FORCE + o[1].split("</answer>")[0] + "</answer>"
            new[s] = torch.tensor(enc(text) + [tok.eos_token_id], dtype=torch.long)
            forced[s] = (len(enc(c)), len(enc(c + FORCE)))
        return new, forced

    def tok_mask(tr, lp):  # 0 on the tokens --force-answer appended (the model did not choose them)
        m = torch.ones_like(lp)
        if tr.get("forced"):
            m[tr["forced"][0]:tr["forced"][1]] = 0
        return m

    def generate_replies(games, it, t):
        """One turn of every game: -> (conversations, reply token ids per game, forced spans or None)."""
        msgs = []
        for ep in games:
            msgs.append(G.conversation(ep, a.k, a.strength, a.player))
        forced = None
        if srv:
            texts, prompts = [], []
            for m in msgs:
                x = proc.apply_chat_template(m, tokenize=False, add_generation_prompt=True)
                texts.append(x)
                prompts.append((x, images_of(m)))
            out, _ = srv.generate(prompts, temperature=1.0, top_p=0.95, top_k=64, max_tokens=a.max_new,
                                  seed=it * 10_000 + t, **ban)
            new = []
            for o in out:
                new.append(torch.tensor(o[0], dtype=torch.long))
            if a.force_answer:
                new, forced = force_answers(texts, msgs, new, it * 10_000 + t)
        else:
            inp = proc.apply_chat_template(msgs, tokenize=True, add_generation_prompt=True, return_dict=True,
                                           return_tensors="pt", padding=True).to(dev)
            with torch.no_grad():
                gen = model.generate(**inp, max_new_tokens=a.max_new, do_sample=True, temperature=1.0, top_p=0.95,
                                     top_k=64)
            new = gen[:, inp["input_ids"].shape[1]:]
        return msgs, new, forced

    last_sec = 25 * 60  # duration guess for the first iteration (--max-minutes, Slurm time limit)
    t_kill = job_end()  # stop cleanly before Slurm kills the job, so the lock is released and a --resume job continues
    finished = None
    for it in range(start, a.iters + 1):
        if a.max_minutes and time.time() - T_START + 1.1 * last_sec > a.max_minutes * 60:
            say(f"stopping before iteration {it} (--max-minutes {a.max_minutes:g}); rerun with --resume to continue")
            break
        if t_kill and time.time() + 1.1 * last_sec > t_kill - 300:
            say(f"stopping before iteration {it}: the job's time limit is near; rerun with --resume to continue")
            break
        t0 = time.time()
        take_lock()
        # ---------------- 1. rollout
        tok.padding_side = "left"
        model.eval()
        games = []
        for s in range(a.games):  # start the games in parallel
            games.append(new_game(s, wait=False))
        for g in games:
            g.wait_ready()
        turns = []  # dicts: msgs, gen ids, combo, prev, state, state_next, slot, t
        prev = [0] * a.games
        t_gen = 0.0  # seconds spent generating replies (the rest of the rollout is the games themselves)
        for t in range(a.turns):
            tg = time.time()
            msgs, new, forced = generate_replies(games, it, t)
            t_gen += time.time() - tg
            for s, (ep, ids) in enumerate(zip(games, new)):
                raw = tok.decode(ids, skip_special_tokens=False)
                fz = forced[s] if srv and a.force_answer else None
                _, reply = G.split_thinking(raw)
                buttons, _, err = G.parse(reply)
                combo, held = G.to_combo(buttons or []) if not err else (0, [])
                state = ram_features(ep.ram)
                ep.history.append((ep.frames, G.answer_text(combo)))
                ep.step(held, dict(reply=reply, error=err, combo=combo, it=it))
                ids = ids[ids != tok.pad_token_id]
                turns.append(dict(msgs=msgs[s], ids=ids.cpu(), truncated=len(ids) >= a.max_new, combo=combo,
                                  prev=prev[s], state=state, state_next=ram_features(ep.ram), slot=s, t=t, err=err,
                                  done=ep.done, forced=fz))
                prev[s] = combo
                if ep.done:
                    ep.finish(dict(algo=a.algo, it=it))
                    games[s] = new_game(s)
                    prev[s] = 0
        for ep in games:
            ep.finish(dict(algo=a.algo, it=it))
        t_roll = time.time() - t0
        take_lock()

        # ---------------- log pi of each generated reply (needed for AIRL; recomputed with grad in the update)
        tok.padding_side = "right"

        def seq_logprob(tr, grad):
            prompt = proc.apply_chat_template(tr["msgs"], tokenize=False, add_generation_prompt=True)
            b = proc(text=[prompt], images=[images_of(tr["msgs"])], return_tensors="pt").to(dev)
            ids = torch.cat([b["input_ids"], tr["ids"][None].to(dev)], 1)
            b["input_ids"], b["attention_mask"] = ids, torch.ones_like(ids)
            if "mm_token_type_ids" in b:
                b["mm_token_type_ids"] = torch.cat([b["mm_token_type_ids"], torch.zeros_like(tr["ids"][None]).to(dev)],
                                                   1)
            with torch.set_grad_enabled(grad):
                logits = model(**b).logits[0, -len(tr["ids"]) - 1:-1].float()
                lp = torch.log_softmax(logits, -1).gather(-1, tr["ids"].to(dev)[:, None]).squeeze(-1)
            return lp  # per-token log-probs of the generated reply

        xs, states, states_next, errs = [], [], [], []
        for tr in turns:
            xs.append(x_of(tr["state"], tr["prev"], tr["combo"]))
            states.append(tr["state"])
            states_next.append(tr["state_next"])
            errs.append(bool(tr["err"]))
        X = np.stack(xs)
        if a.algo == "airl":
            with torch.no_grad():
                lps = []
                for tr in turns:
                    lps.append(float(seq_logprob(tr, False).mean()))
                logpi = torch.tensor(lps)
        else:
            logpi = torch.zeros(len(turns))

        # ---------------- 2. rewards
        ag = {"x": torch.tensor(nz(X)), "s": torch.tensor((np.stack(states) - smu) / ssd),
              "s2": torch.tensor((np.stack(states_next) - smu) / ssd), "logpi": logpi}
        jstats = {}
        if a.algo == "density":
            r = torch.tensor(gmm.score_samples(nz(X)), dtype=torch.float32).clamp(-20, 20)
        else:
            hum["logpi"] = torch.full((len(hum["x"]),), float(logpi.mean()))
            if hum_val is not None:  # before the update: this iteration's agent turns are unseen, so are hum_val
                hum_val["logpi"] = torch.full((len(hum_val["x"]),), float(logpi.mean()))
                vh, va = judge_accuracy(judge, hum_val, ag, a.gamma)
                jstats.update(judge_heldout_human=vh, judge_heldout_agent=va, judge_heldout_balanced=(vh + va) / 2)
            ag_buf = (ag_buf + [ag])[-a.judge_replay:]
            ag_tr = {}
            for k_ in ag:
                parts = []
                for b in ag_buf:
                    parts.append(b[k_])
                ag_tr[k_] = torch.cat(parts)
            acc_h, acc_a = judge_update(judge, jopt, hum, ag_tr, a.gamma, steps=a.judge_steps)
            jstats.update(judge_acc_human=acc_h, judge_acc_agent=acc_a)
            with torch.no_grad():
                lg = judge.logit(ag["x"], ag["s"], ag["s2"], ag["logpi"], a.gamma)
                r = (-F.logsigmoid(-lg) if a.algo == "gail" else lg).clamp(-10, 10)
        if a.format_reward is not None:
            r = torch.where(torch.tensor(errs), torch.tensor(a.format_reward, dtype=r.dtype), r)
        # discounted turn returns per game slot, then normalised
        ret = torch.zeros(len(turns))
        for s in range(a.games):
            idx = []
            for i, tr in enumerate(turns):
                if tr["slot"] == s:
                    idx.append(i)
            g = 0.0
            for i in reversed(idx):
                g = float(r[i]) + a.gamma * g * (0.0 if turns[i]["done"] else 1.0)
                ret[i] = g
        adv = (ret - ret.mean()) / (ret.std() + 1e-6)
        if a.format_mask:  # malformed replies get no policy gradient (only the KL pull back to --init)
            adv = torch.where(torch.tensor(errs), torch.zeros_like(adv), adv)

        # ---------------- format guard: these rollouts came from the current LoRA (before this iteration's update)
        fe = float(np.mean(errs))
        guard_hit = bool(a.format_guard) and fe > a.format_guard
        if a.format_guard and not guard_hit:
            clean = lora_state(params, clone=True)
            torch.save(clean, f"{od}/lora_clean.pt")
        elif guard_hit:
            load_into(params, clean)
            kb = a.kl_beta
            if ref is not None:  # (no reference policy without --kl-beta: then only the rollback)
                a.kl_beta = min(a.kl_beta_max, max(2 * a.kl_beta, 0.01))
            say(f"format guard: {fe:.1%} malformed > {a.format_guard:.1%}; update skipped, LoRA rolled back to the "
                f"last clean one, kl-beta {kb:g} -> {a.kl_beta:g}")
            if srv:
                push_lora()

        # ---------------- 3. policy update (REINFORCE, one pass), DAPO practices (Yu et al. 2025):
        # overlong filtering (replies cut at --max-new are left out of the loss: their reward is noise, not a
        # verdict on the reasoning) and token-level normalisation (every generated token weighs the same,
        # instead of every reply, so long replies are not down-weighted)
        model.train()
        keep = []
        if not guard_hit:
            for j in range(len(turns)):
                if not turns[j]["truncated"] and len(turns[j]["ids"]) > 0:
                    keep.append(j)
        n_kept = 0
        for j in keep:
            n_kept += len(turns[j]["ids"])
        n_tok = max(1, n_kept)
        ref_lp = {}
        if a.kl_beta:  # log-probs under the --init policy: swap its LoRA in, no grad, swap back
            cur = {}
            for nm, p in params.items():
                cur[nm] = p.detach().clone()
            with torch.no_grad():
                for nm, p in params.items():
                    p.copy_(ref[nm])
                model.eval()
                for j in keep:
                    ref_lp[j] = seq_logprob(turns[j], False)
                for nm, p in params.items():
                    p.copy_(cur[nm])
            model.train()
            del cur
        kl_sum = 0.0
        for j in rng.permutation(keep):
            lp = seq_logprob(turns[j], True)
            m = tok_mask(turns[j], lp)
            loss = -adv[j] * (lp * m).sum() / n_tok
            if a.kl_beta:
                d = ref_lp[j] - lp
                kl = ((torch.exp(d) - d - 1) * m).sum()  # k3 estimate of KL(policy || init), per token, summed
                loss = loss + a.kl_beta * kl / n_tok
                kl_sum += float(kl)
            loss.backward()
        torch.nn.utils.clip_grad_norm_(list(params.values()), 1.0)
        opt.step()
        opt.zero_grad(set_to_none=True)
        if srv:
            push_lora()

        # ---------------- 4. human-likeness of this iteration's turns
        hl = human_likeness(nz(X), nz(Xv))
        combos, n_forced, n_trunc, deaths, n_new, n_reasoning = [], 0, 0, 0, [], 0
        for tr in turns:
            combos.append(tr["combo"])
            n_forced += bool(tr.get("forced"))
            n_trunc += tr["truncated"]
            deaths += tr["done"]
            n_new.append(len(tr["ids"]))
            n_reasoning += "<perception>" in G.split_thinking(tok.decode(tr["ids"]))[1]
        hist_a = np.bincount(combos, minlength=N_ACT) + 1
        hist_h = np.bincount(Xv[:, -N_ACT:].argmax(1), minlength=N_ACT) + 1
        pa, ph = hist_a / hist_a.sum(), hist_h / hist_h.sum()
        matched = {}
        if Xv_m is not None and len(Xv_m):
            hm = np.bincount(Xv_m[:, -N_ACT:].argmax(1), minlength=N_ACT) + 1
            hm = hm / hm.sum()
            matched = dict(human_likeness_matched=human_likeness(nz(X), nz(Xv_m)),
                           action_kl_matched=float((hm * np.log(hm / pa)).sum()))
        rec = dict(it=it, turns=len(turns), format_err=fe, forced_share=n_forced / len(turns),
                   truncated=n_trunc / len(turns),
                   reward=float(r.mean()), human_likeness_clf_acc=hl, action_kl=float((ph * np.log(ph / pa)).sum()),
                   deaths=int(deaths), sec_rollout=round(t_roll), sec_generate=round(t_gen),
                   sec=round(time.time() - t0),
                   mean_new_tokens=float(np.mean(n_new)),
                   reasoning_share=n_reasoning / len(turns),
                   **({"kl_to_init": kl_sum / n_tok} if a.kl_beta else {}), **matched, **jstats,
                   **({"guard_rollback": guard_hit, "kl_beta": a.kl_beta} if a.format_guard else {}))
        log.append(rec)
        hl_hist.append(hl)
        say(json.dumps(rec))
        json.dump(dict(args=vars(a), log=log), open(f"{od}/log.json", "w"), indent=1)
        torch.save(lora_state(params), f"{od}/lora_last.pt")
        st = dict(it=it, kl_beta=a.kl_beta, lora=lora_state(params), opt=opt.state_dict(), log=log,
                  hl_hist=hl_hist, ep_count=ep_count[0], rng=rng.bit_generator.state)
        if a.algo != "density":
            st.update(judge=judge.state_dict(), jopt=jopt.state_dict())
        torch.save(st, state_path + ".tmp")
        os.replace(state_path + ".tmp", state_path)
        last_sec = time.time() - t0
        if it % 5 == 0:
            torch.save(lora_state(params), f"{od}/lora_it{it:03d}.pt")
        if a.patience and len(hl_hist) > a.patience and \
                max(hl_hist[-a.patience - 1:]) - min(hl_hist[-a.patience - 1:]) < 0.01:
            say(f"stop: human-likeness flat over {a.patience} iterations")
            finished = f"human-likeness flat at iteration {it}"
            break
        if it == a.iters:
            finished = f"all {a.iters} iterations"
    if finished:
        open(f"{od}/DONE", "w").write(finished)
    if os.path.exists(lock) and open(lock).read().strip() == os.environ.get("SLURM_JOB_ID", "local"):
        os.remove(lock)  # release (a killed run leaves it to go stale after 40 min)
    if srv:
        srv.close()


if __name__ == "__main__":
    main()
