# ----------------------------------------------------------------------------------------- game-state features
def ram_features(ram):
    """RAM [2048] -> float vector: Mario (x on screen, y, x speed, y speed, airborne, big), 5 nearest enemies."""
    from mjg.objects import oracle_objects, TYPE_MARIO, TYPE_GOOMBA, TYPE_KOOPA, TYPE_ENEMY
    from audit_dataset import A  # experiments/odysseus: RAM name -> address map used by oracle_objects
    r = {}
    for k, addr in A.items():
        r[k] = int(ram[addr])
    objs = oracle_objects(r)
    m = []
    enemies = []
    for o in objs:
        if o.type == TYPE_MARIO:
            m.append(o)
    mx, my = (m[0].center if m else (0.0, 0.0))
    for o in objs:
        if o.type in (TYPE_GOOMBA, TYPE_KOOPA, TYPE_ENEMY):
            enemies.append(o.center)
    sx = lambda v: (v - 256 if v > 127 else v) / 40.0
    out = [mx / 256, my / 240, sx(int(ram[0x57])), sx(int(ram[0x9F])), float(ram[0x1D] != 0), float(ram[0x754] == 0)]
    en = sorted(enemies, key=lambda c: abs(c[0] - mx))[:N_ENEMY]
    for i in range(N_ENEMY):
        out += [(en[i][0] - mx) / 256, (en[i][1] - my) / 240, 1.0] if i < len(en) else [0.0, 0.0, 0.0]
    return np.array(out, np.float32)


def x_of(state, prev_combo, combo):
    return np.concatenate([state, np.eye(N_ACT, dtype=np.float32)[prev_combo], np.eye(N_ACT, dtype=np.float32)[combo]])


def read_index(data_dir):
    """The rows of <data_dir>/index.jsonl (one per play)."""
    rows = []
    for line in open(f"{data_dir}/index.jsonl"):
        rows.append(json.loads(line))
    return rows


def levels_of(data_dir):
    """Sorted distinct levels of the plays in an SFT data folder."""
    levels = set()
    for row in read_index(data_dir):
        levels.add(row["level"])
    return sorted(levels)


def human_turns(split, max_plays=0, with_turn=False, data_dir=None):
    """(x, s, s_next) per human turn of the SFT data (data_dir: a folder with index.jsonl + <split>/<play>.npz;
    default SFT_DATA = sub-01), with RAM from features/ram_full; with_turn: also the turn's index in its play
    (0 = first turn after the level start), to compare with the agent's turns from the same game phase."""
    data_dir = data_dir or SFT_DATA
    plays = []
    for row in read_index(data_dir):
        if row["split"] == split and row.get("n_turns"):
            plays.append(row)
    if max_plays:
        plays = plays[:max_plays]
    X, S, S2, TI = [], [], [], []
    for row in plays:
        z = np.load(f"{data_dir}/{split}/{row['play_id']}.npz")
        rp = f"{RAM_DIR}/{row['play_id']}.npz"
        if not os.path.exists(rp):
            continue
        ram = np.load(rp)["ram"]
        t, combo = z["t"], z["combo"]
        st = []
        for k in t:  # state before the human acts at t
            st.append(ram_features(ram[min(max(int(k) - 1, 0), len(ram) - 1)]))
        for i in range(len(t)):
            prev = int(combo[i - 1]) if i else 0
            X.append(x_of(st[i], prev, int(combo[i])))
            S.append(st[i])
            S2.append(st[min(i + 1, len(t) - 1)])
            TI.append(i)
    out = (np.stack(X), np.stack(S), np.stack(S2))
    return out + (np.array(TI),) if with_turn else out


# ----------------------------------------------------------------------------------------- judges
class Judge(nn.Module):
    def __init__(self, d_x, d_s, airl):
        super().__init__()
        mlp = lambda d: nn.Sequential(nn.Linear(d, 128), nn.ReLU(), nn.Linear(128, 128), nn.ReLU(), nn.Linear(128, 1))
        self.airl = airl
        self.g = mlp(d_x)
        if airl:
            self.h = mlp(d_s)

    def f(self, x, s, s2, gamma):
        out = self.g(x).squeeze(-1)
        return out + gamma * self.h(s2).squeeze(-1) - self.h(s).squeeze(-1) if self.airl else out

    def logit(self, x, s, s2, logpi, gamma):
        return self.f(x, s, s2, gamma) - (logpi if self.airl else 0.0)


def judge_accuracy(judge, hum, ag, gamma):
    """Share of human turns called human and of agent turns called agent (no update)."""
    with torch.no_grad():
        acc_h = float((judge.logit(hum["x"], hum["s"], hum["s2"], hum["logpi"], gamma) > 0).float().mean())
        acc_a = float((judge.logit(ag["x"], ag["s"], ag["s2"], ag["logpi"], gamma) < 0).float().mean())
    return acc_h, acc_a


def judge_update(judge, opt, hum, ag, gamma, steps=4, bs=256, gp=1.0):
    """hum/ag: dicts of tensors x, s, s2, logpi (logpi of human turns under the current policy is unknown:
    approximated by the agent batch mean, as a constant; GAIL ignores it)."""
    for _ in range(steps):
        ih = torch.randint(len(hum["x"]), (bs,))
        ia = torch.randint(len(ag["x"]), (bs,))
        xh = hum["x"][ih].clone().requires_grad_(True)
        lh = judge.logit(xh, hum["s"][ih], hum["s2"][ih], hum["logpi"][ih], gamma)
        la = judge.logit(ag["x"][ia], ag["s"][ia], ag["s2"][ia], ag["logpi"][ia], gamma)
        loss = F.binary_cross_entropy_with_logits(lh, torch.ones_like(lh)) + \
            F.binary_cross_entropy_with_logits(la, torch.zeros_like(la))
        g, = torch.autograd.grad(lh.sum(), xh, create_graph=True)
        loss = loss + gp * g.pow(2).sum(1).mean()
        opt.zero_grad()
        loss.backward()
        opt.step()
    return judge_accuracy(judge, hum, ag, gamma)


def human_likeness(Xa, Xh):
    """Cross-validated accuracy of a logistic classifier agent vs human on x (0.5 = indistinguishable)."""
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import cross_val_score
    n = min(len(Xa), len(Xh))
    if n < 4:  # too few turns to cross-validate
        return float("nan")
    ih = np.random.default_rng(0).choice(len(Xh), n, replace=False)
    X = np.concatenate([Xa[:n], Xh[ih]])
    y = np.r_[np.zeros(n), np.ones(n)]
    return float(cross_val_score(LogisticRegression(max_iter=2000, C=1.0), X, y, cv=min(5, n)).mean())


